"""Core orchestration engine for NoteDigest."""
import json
from pathlib import Path
from typing import Dict, Any, Optional

from .models import DigestResult
from .extractor import NoteExtractor


class NoteDigestEngine:
    """Orchestrates ingestion, extraction, and markdown digest generation."""

    def __init__(self):
        self.extractor = NoteExtractor()

    def process(self, text: str, title: Optional[str] = None) -> DigestResult:
        """Process raw unstructured notes into a structured digest."""
        clean_text = text.strip()
        words = len(clean_text.split())

        # Determine title
        if not title:
            lines = [l.strip() for l in clean_text.splitlines() if l.strip()]
            if lines and lines[0].startswith("#"):
                title = lines[0].lstrip("#").strip()
            else:
                title = "Meeting / Notes Digest"

        actions = self.extractor.extract_action_items(clean_text)
        decisions = self.extractor.extract_decisions(clean_text)
        questions = self.extractor.extract_open_questions(clean_text)
        key_points = self.extractor.extract_key_points(clean_text)

        # Build executive summary
        summary_sentences = []
        summary_sentences.append(f"Structured analysis of {words} words.")
        if decisions:
            summary_sentences.append(f"{len(decisions)} key decision(s) established.")
        if actions:
            summary_sentences.append(f"{len(actions)} immediate action item(s) identified.")
        if questions:
            summary_sentences.append(f"{len(questions)} unresolved question(s) flagged for follow-up.")

        exec_summary = " ".join(summary_sentences)

        return DigestResult(
            title=title,
            executive_summary=exec_summary,
            decisions=decisions,
            action_items=actions,
            key_points=key_points,
            open_questions=questions,
            raw_word_count=words
        )

    def format_markdown(self, result: DigestResult) -> str:
        """Format digest result as a clean, structured Markdown document."""
        md = []
        md.append(f"# {result.title}")
        md.append("")
        md.append("> **Generated by NoteDigest (Governed by OpenClone)**")
        md.append("")
        md.append("## Executive Summary")
        md.append(result.executive_summary)
        md.append("")

        if result.decisions:
            md.append("## Key Decisions")
            for d in result.decisions:
                md.append(f"- **[{d.id}]** {d.summary}")
            md.append("")

        if result.action_items:
            md.append("## Action Items & Ownership")
            md.append("| ID | Action Description | Owner | Deadline | Priority |")
            md.append("|:---|:---|:---|:---|:---|")
            for a in result.action_items:
                dl = a.deadline or "TBD"
                md.append(f"| `{a.id}` | {a.description} | **{a.owner}** | {dl} | `{a.priority}` |")
            md.append("")

        if result.open_questions:
            md.append("## Open Questions & Blockers")
            for q in result.open_questions:
                md.append(f"- [ ] {q}")
            md.append("")

        if result.key_points:
            md.append("## Discussion Topics")
            for kp in result.key_points:
                md.append(f"### {kp.topic}")
                md.append(kp.details)
                md.append("")

        return "\n".join(md).strip() + "\n"

    def to_dict(self, result: DigestResult) -> Dict[str, Any]:
        """Convert digest result to dictionary."""
        return {
            "title": result.title,
            "executive_summary": result.executive_summary,
            "raw_word_count": result.raw_word_count,
            "decisions": [{"id": d.id, "summary": d.summary} for d in result.decisions],
            "action_items": [
                {
                    "id": a.id,
                    "description": a.description,
                    "owner": a.owner,
                    "deadline": a.deadline,
                    "priority": a.priority
                }
                for a in result.action_items
            ],
            "open_questions": result.open_questions,
            "key_points": [{"topic": kp.topic, "details": kp.details} for kp in result.key_points]
        }
