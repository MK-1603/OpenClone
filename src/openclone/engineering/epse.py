"""
OpenClone Engineering Problem-Solving Engine (EPSE).
Coordinates the 18-stage engineering problem analysis, solution generation, and evaluation lifecycle.
"""

from __future__ import annotations
import uuid
from dataclasses import dataclass, field
from enum import Enum
from typing import List, Optional, Dict, Any
from datetime import datetime, timezone
from openclone.engineering.models import MasterSector, KnowledgeUnit
from openclone.engineering.graph import KnowledgeGraphEngine
from openclone.engineering.capabilities import CapabilityRegistry, EngineeringCapability


class ProblemCategory(str, Enum):
    DEVELOPMENT = "development"
    DEBUGGING = "debugging"
    ARCHITECTURE = "architecture"
    DESIGN = "design"
    PERFORMANCE = "performance"
    SECURITY = "security"
    AI_ENGINEERING = "ai_engineering"
    DATA = "data"
    DATABASE = "database"
    INFRASTRUCTURE = "infrastructure"
    DEPLOYMENT = "deployment"
    INTEGRATION = "integration"
    MIGRATION = "migration"
    RELIABILITY = "reliability"
    MODERNIZATION = "modernization"
    TECH_DEBT = "tech_debt"


@dataclass
class SolutionAlternative:
    """Represents an evaluated solution option."""
    name: str
    description: str
    feasibility_score: float  # 0.0 to 1.0
    security_score: float     # 0.0 to 1.0
    performance_score: float  # 0.0 to 1.0
    complexity_score: float   # 0.0 (high complexity) to 1.0 (low complexity/simple)
    pros: List[str] = field(default_factory=list)
    cons: List[str] = field(default_factory=list)
    trade_offs: str = ""

    @property
    def composite_score(self) -> float:
        # Weighted composite score
        return round(
            (0.30 * self.feasibility_score) +
            (0.25 * self.security_score) +
            (0.25 * self.performance_score) +
            (0.20 * self.complexity_score),
            3
        )


@dataclass
class ProblemSolvingPlan:
    """Execution plan generated by EPSE for downstream orchestration."""
    plan_id: str
    problem_title: str
    category: ProblemCategory
    primary_sector: MasterSector
    root_cause_analysis: str
    discovered_knowledge: List[str]
    selected_solution: SolutionAlternative
    alternatives: List[SolutionAlternative]
    required_capabilities: List[str]
    recommended_agents: List[str]
    testing_strategy: List[str]
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        return {
            "plan_id": self.plan_id,
            "problem_title": self.problem_title,
            "category": self.category.value,
            "primary_sector": self.primary_sector.value,
            "root_cause_analysis": self.root_cause_analysis,
            "discovered_knowledge": self.discovered_knowledge,
            "selected_solution": {
                "name": self.selected_solution.name,
                "composite_score": self.selected_solution.composite_score,
                "trade_offs": self.selected_solution.trade_offs,
            },
            "alternatives_count": len(self.alternatives),
            "required_capabilities": self.required_capabilities,
            "recommended_agents": self.recommended_agents,
            "testing_strategy": self.testing_strategy,
            "created_at": self.created_at,
        }


class EngineeringProblemSolvingEngine:
    """
    Executes problem decomposition, technical research, solution generation,
    trade-off evaluation, and agent assignment.
    """

    SECTOR_CLASSIFICATION_RULES = {
        ProblemCategory.ARCHITECTURE: MasterSector.EIS_04,
        ProblemCategory.DATABASE: MasterSector.EIS_08,
        ProblemCategory.SECURITY: MasterSector.EIS_11,
        ProblemCategory.AI_ENGINEERING: MasterSector.EIS_05,
        ProblemCategory.PERFORMANCE: MasterSector.EIS_13,
        ProblemCategory.DEPLOYMENT: MasterSector.EIS_10,
        ProblemCategory.DEVELOPMENT: MasterSector.EIS_03,
        ProblemCategory.INTEGRATION: MasterSector.EIS_14,
        ProblemCategory.RELIABILITY: MasterSector.EIS_13,
    }

    def __init__(self, graph_engine: KnowledgeGraphEngine, capability_registry: CapabilityRegistry):
        self.graph = graph_engine
        self.capabilities = capability_registry

    def solve_problem(
        self,
        problem_title: str,
        problem_description: str,
        category: ProblemCategory,
        constraints: Optional[List[str]] = None
    ) -> ProblemSolvingPlan:
        plan_id = f"EPSE-{uuid.uuid4().hex[:6].upper()}"

        # Stage 1-4: Classify and identify primary sector
        primary_sector = self.SECTOR_CLASSIFICATION_RULES.get(category, MasterSector.EIS_03)

        # Stage 5: Root-cause / domain analysis
        root_cause = f"Root analysis for {category.value} problem '{problem_title}': Requires structural resolution in sector {primary_sector.value}."

        # Stage 6-7: Knowledge Discovery
        relevant_units = self.graph.search_knowledge(f"{problem_title} {problem_description}", limit=5)
        discovered_knowledge = [u.id for u in relevant_units]

        # Stage 8-11: Solution Generation & Multi-Attribute Evaluation
        alt_a = SolutionAlternative(
            name=f"Standard Recommended Pattern for {category.value}",
            description=f"Industry best-practice implementation using verified patterns from {primary_sector.value}.",
            feasibility_score=0.95,
            security_score=0.90,
            performance_score=0.90,
            complexity_score=0.85,
            pros=["Adheres to canonical standards", "Zero unverified dependencies"],
            cons=["Requires rigorous test validation"],
            trade_offs="Balances developer velocity with strict type safety and security baseline compliance."
        )
        alt_b = SolutionAlternative(
            name="Quick-Fix / Workaround Approach",
            description="Minimal patch without structural refactoring.",
            feasibility_score=0.80,
            security_score=0.60,
            performance_score=0.70,
            complexity_score=0.90,
            pros=["Fast execution"],
            cons=["Accumulates technical debt", "Lower security rating"],
            trade_offs="Sacrifices long-term maintainability for rapid resolution."
        )

        alternatives = [alt_a, alt_b]
        alternatives.sort(key=lambda a: a.composite_score, reverse=True)
        selected_solution = alternatives[0]

        # Stage 12-14: Capability Identification & Agent Assignment
        required_caps: List[str] = []
        recommended_agents: List[str] = []

        if category == ProblemCategory.DATABASE:
            required_caps.append("CAP-DB-001")
        elif category == ProblemCategory.SECURITY:
            required_caps.append("CAP-SEC-001")
        elif category == ProblemCategory.ARCHITECTURE:
            required_caps.append("CAP-ARCH-001")
        elif category == ProblemCategory.AI_ENGINEERING:
            required_caps.append("CAP-AI-001")
        else:
            required_caps.append("CAP-DEV-001")

        # Always require QA
        required_caps.append("CAP-QA-001")

        for cap_id in required_caps:
            agents = self.capabilities.find_capable_agents(cap_id)
            for ag in agents:
                if ag not in recommended_agents:
                    recommended_agents.append(ag)

        # Stage 15: Testing Strategy
        testing_strategy = [
            f"Unit test suite for {primary_sector.value} domain boundaries",
            "Integration test against simulated failure states",
            "SaaS Security Baseline 19-point audit",
            "Independent Verifier Goldfish attestation (CAP-VER-001)",
        ]

        return ProblemSolvingPlan(
            plan_id=plan_id,
            problem_title=problem_title,
            category=category,
            primary_sector=primary_sector,
            root_cause_analysis=root_cause,
            discovered_knowledge=discovered_knowledge,
            selected_solution=selected_solution,
            alternatives=alternatives,
            required_capabilities=required_caps,
            recommended_agents=recommended_agents,
            testing_strategy=testing_strategy
        )
